// The shop items, built from blocks. Sizes are in pixels (16 = one floor tile).
// Floor items stand on y=0 and are centred on x/z.
// Wall items hang on a wall: their back is at z=0 and they stick out towards +z; y=0 is the hanging height.

const WOOD = '#B9784A', WOOD_D = '#8A5634', WOOD_L = '#D9A066';
const WHITE = '#FFFFFF', OFF = '#F2EEE8', INK = '#2B1E3A';

function ring(cx, y0, cz, r, h, color, step = 1) {
  // A round-ish disc made of a few stacked rectangles (a "pixel circle").
  const out = [];
  for (let i = 0; i < r; i += step) {
    const half = Math.round(Math.sqrt(Math.max(0.25, r * r - (i + 0.5) * (i + 0.5))));
    out.push([cx, y0, cz + i + step / 2, half * 2, h, step, color]);
    out.push([cx, y0, cz - i - step / 2, half * 2, h, step, color]);
  }
  return out;
}

function wallDisc(cx, cy, r, d, color, z0 = 0) {
  // A round-ish shape that hangs on a wall (circle in x/y).
  const out = [];
  for (let i = 0; i < r; i++) {
    const half = Math.round(Math.sqrt(Math.max(0.25, r * r - (i + 0.5) * (i + 0.5))));
    out.push([cx, cy + i, z0 + d / 2, half * 2, 1, d, color]);
    out.push([cx, cy - i - 1, z0 + d / 2, half * 2, 1, d, color]);
  }
  return out;
}

