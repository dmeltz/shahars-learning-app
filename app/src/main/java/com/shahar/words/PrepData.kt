enum class Pos { VERB, NOUN, ADJ, OTHER }

/**
 * A Hebrew word to learn, with niqqud. [sentence] always contains [form] exactly as written, so it can be
 * blanked out for "which word fits?" questions. [syn] fits in its place in the sentence. [opp] is its opposite.
 */
data class HeWord(
    val word: String,
    val meaning: String,
    val sentence: String,
    val pos: Pos,
    val syn: String = "",
    val opp: String = "",
    val fromSample: Boolean = false,
    /** The word without niqqud. Progress is saved under it, so adding niqqud kept what he already learned. */
    val id: String = word,
    /** How the word is written inside [sentence] (after "הַ" the first letter gets a dagesh). */
    val form: String = word,
)

private fun v(word: String, meaning: String, sentence: String, syn: String = "", opp: String = "", s: Boolean = false, id: String = word, form: String = word) =
    HeWord(word, meaning, sentence, Pos.VERB, syn, opp, s, id, form)
private fun n(word: String, meaning: String, sentence: String, syn: String = "", opp: String = "", s: Boolean = false, id: String = word, form: String = word) =
    HeWord(word, meaning, sentence, Pos.NOUN, syn, opp, s, id, form)
private fun a(word: String, meaning: String, sentence: String, syn: String = "", opp: String = "", s: Boolean = false, id: String = word, form: String = word) =
    HeWord(word, meaning, sentence, Pos.ADJ, syn, opp, s, id, form)
private fun o(word: String, meaning: String, sentence: String, syn: String = "", opp: String = "", s: Boolean = false, id: String = word, form: String = word) =
    HeWord(word, meaning, sentence, Pos.OTHER, syn, opp, s, id, form)

