enum class Pos { VERB, NOUN, ADJ, OTHER }

/**
 * A Hebrew word to learn. [sentence] always contains [word] exactly as written, so it can be
 * blanked out for "which word fits?" questions. [syn] fits in its place in the sentence. [opp] is its opposite.
 */
data class HeWord(
    val word: String,
    val meaning: String,
    val sentence: String,
    val pos: Pos,
    val syn: String = "",
    val opp: String = "",
    val fromSample: Boolean = false,
)

private fun v(word: String, meaning: String, sentence: String, syn: String = "", opp: String = "", s: Boolean = false) =
    HeWord(word, meaning, sentence, Pos.VERB, syn, opp, s)
private fun n(word: String, meaning: String, sentence: String, syn: String = "", opp: String = "", s: Boolean = false) =
    HeWord(word, meaning, sentence, Pos.NOUN, syn, opp, s)
private fun a(word: String, meaning: String, sentence: String, syn: String = "", opp: String = "", s: Boolean = false) =
    HeWord(word, meaning, sentence, Pos.ADJ, syn, opp, s)
private fun o(word: String, meaning: String, sentence: String, syn: String = "", opp: String = "", s: Boolean = false) =
    HeWord(word, meaning, sentence, Pos.OTHER, syn, opp, s)

